import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import type { ModelProfile } from "@amo-studio/protocol";
import { removeTempDir } from "@amo-studio/testkit";
import { HostService } from "../service.js";
import { Store } from "../store/store.js";
import { CodexRuntime } from "./codex/codex-runtime.js";
import { FakeServers } from "./codex/fake-servers.test-support.js";

const profiles: ModelProfile[] = [{ id: "test", label: "测试", runtime: "codex", provider: null, model: "test-model" }];
let folder: string, store: Store, servers: FakeServers;
afterEach(async () => { vi.restoreAllMocks(); await servers?.close(); store?.close(); if (folder) removeTempDir(folder); });

it("rechecks the frozen inbox row after cold resume and never dispatches an expired v1 payload", async () => {
  folder = mkdtempSync(join(tmpdir(), "amo-studio-test-dispatch-validity-"));
  store = new Store(join(folder, "studio.db")); servers = new FakeServers(profiles);
  const runtime = new CodexRuntime({ store, servers, profiles });
  const service = new HostService(store, runtime, profiles, { commonDir: join(folder, "common") });
  const workspace = store.addWorkspace({ name: "项目", path: folder });
  const top = store.createTask({ title: "主控", workspaceId: workspace.id, lead: true });
  const child = store.createTask({ title: "执行", workspaceId: workspace.id, managerTaskId: top.id });
  const manager = await service.tasks.addSession(top.id, { profileId: "test" });
  const worker = await service.tasks.addSession(child.id, { profileId: "test" });
  service.sessions.inbox.pause(worker.id);
  const draft = service.sharedContext.save(manager.id, { rootTaskId: top.id, baseRevision: 0, title: "版本", body: "旧版专用内容", changeNote: "v1", sources: [{ kind: "user_requirement", source: "用户" }] });
  const v1 = service.sharedContext.publishVersion(manager.id, draft.id, draft.revision);
  service.sharedContext.apply(manager.id, { contextId: draft.id, version: 1, taskIds: [child.id] });
  await service.sessions.inbox.put(worker.id, "业务待发送", manager.id, "i-resume-race");
  const frozen = store.getItem("i-resume-race");
  expect(frozen).toMatchObject({ delivery: "held", text: expect.stringContaining("旧版专用内容") });
  let release!: () => void, entered!: () => void;
  const barrier = new Promise<void>((resolve) => { release = resolve; });
  const atBarrier = new Promise<void>((resolve) => { entered = resolve; });
  const ensure = servers.ensure.bind(servers);
  vi.spyOn(servers, "ensure").mockImplementationOnce(async (id) => { entered(); await barrier; return ensure(id); });
  const sending = service.sessions.resend(worker.id, "i-resume-race");
  await atBarrier;
  const next = service.sharedContext.save(manager.id, { rootTaskId: top.id, baseRevision: v1.revision, title: "版本", body: "新版专用内容", changeNote: "v2", sources: [{ kind: "user_requirement", source: "用户" }] });
  service.sharedContext.publishVersion(manager.id, next.id, next.revision);
  service.sharedContext.apply(manager.id, { contextId: draft.id, version: 2, taskIds: [child.id] });
  await vi.waitFor(() => expect(store.getItem("i-resume-race")).toHaveProperty("delivery", "expired"));
  release();
  await expect(sending).rejects.toThrow(/失效|过期/);
  expect(store.getItem("i-resume-race")).toMatchObject({ delivery: "expired", text: frozen?.type === "user" ? frozen.text : "" });
  expect(servers.fakes.get("test")?.calls.filter((c) => c.method === "turn/start" && JSON.stringify(c.params).includes("旧版专用内容")) ?? []).toHaveLength(0);
  const replacements = store.listItems(worker.id).filter((i) => i.type === "user" && i.replacesItemId === "i-resume-race");
  expect(replacements).toHaveLength(1);
  expect(replacements[0]).toMatchObject({ delivery: "held", text: expect.stringContaining("新版专用内容") });
  await service.sessions.inbox.sendNow(worker.id, replacements[0]!.id);
  const transported = servers.fakes.get("test")!.calls.filter((c) => c.method === "turn/start" && JSON.stringify(c.params).includes("业务待发送"));
  expect(transported).toHaveLength(1);
  expect(JSON.stringify(transported[0]!.params)).toContain("新版专用内容");
  expect(JSON.stringify(transported[0]!.params)).not.toContain("旧版专用内容");
  await service.sessions.interrupt(worker.id);
});

