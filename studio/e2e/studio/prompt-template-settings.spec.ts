import { selectSettingsPage } from "../support/settings.js";
import { expect, test } from "@playwright/test";
import type { PromptTemplate, Workspace } from "@amo-studio/protocol";
import { launchStudio, screenshot, type Studio } from "../support/studio.js";

let studio: Studio | undefined;
test.afterEach(async () => { await studio?.close(); studio = undefined; });

test("settings manages global and project prompt templates", async () => {
  studio = await launchStudio();
  const { page, app } = studio;
  const alpha = await studio.api<Workspace>("POST", "/api/workspaces", { path: studio.workspace("alpha") });
  const beta = await studio.api<Workspace>("POST", "/api/workspaces", { path: studio.workspace("beta") });
  await studio.api("POST", "/api/prompt-templates", { title: "每日巡检", body: "检查近期改动" });
  await studio.api("POST", "/api/prompt-templates", { title: "项目检查", body: "只检查 beta", workspaceId: beta.id });
  await page.getByRole("button", { name: "设置", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "设置", exact: true });
  await settings.getByRole("button", { name: "模型与会话", exact: true }).click();
  await selectSettingsPage(settings, "提示词模板");
  await expect(settings.getByRole("tab", { name: "提示词模板", exact: true })).toBeVisible();
  await settings.getByLabel("搜索设置").pressSequentially("template");
  await expect(settings.getByLabel("搜索设置")).toHaveValue("template");
  await expect(settings.getByLabel("搜索设置")).toBeFocused();
  await expect(settings.getByRole("tab")).toHaveCount(1);
  await selectSettingsPage(settings, "提示词模板");
  const panel = settings.getByTestId("prompt-manager");
  await expect(panel.getByTestId("prompt-item")).toHaveCount(2);
  await expect(panel.getByTestId("prompt-item").filter({ hasText: "项目检查" })).toContainText("beta");
  await expect(panel.getByTestId("prompt-ok")).toHaveCount(0);
  await panel.getByLabel("搜索模板").fill("每日");
  await panel.getByLabel("搜索模板").press("Enter");
  await expect(settings).toBeVisible();
  await expect(panel.getByTestId("prompt-preview")).toContainText("检查近期改动");
  await panel.getByLabel("搜索模板").fill("");
  await panel.getByTestId("prompt-new").click();
  await panel.getByLabel("模板标题").fill("发布检查");
  await panel.getByLabel("模板内容").fill("检查构建与发布说明\n确认项目范围");
  await panel.getByLabel("在哪里出现").selectOption(alpha.id);
  await panel.getByTestId("prompt-save").click();
  await expect(panel.getByTestId("prompt-item")).toHaveCount(3);
  await expect(panel.getByTestId("prompt-preview")).toContainText("alpha");
  await settings.getByLabel("清空设置搜索").click();
  await page.evaluate(() => { document.documentElement.dataset.theme = "dark"; });
  await screenshot(app, "studio", "prompt-template-settings-dark", page);
  await page.evaluate(() => { document.documentElement.dataset.theme = "light"; });
  await screenshot(app, "studio", "prompt-template-settings-light", page);
  await settings.getByRole("button", { name: "关闭设置", exact: true }).click();
  await page.evaluate(() => { localStorage.setItem("amo.settings.size", JSON.stringify({ w: 640, h: 460 })); });
  await page.getByRole("button", { name: "设置", exact: true }).click();
  await expect(panel.getByTestId("prompt-preview")).toContainText("发布检查");
  await screenshot(app, "studio", "prompt-template-settings-small", page);
  await panel.getByRole("button", { name: "编辑", exact: true }).click();
  await panel.getByLabel("模板内容").fill("更新后的发布检查");
  await panel.getByLabel("在哪里出现").selectOption("");
  await panel.getByLabel("模板内容").press("Control+Enter");
  await expect(panel.getByTestId("prompt-preview")).toContainText("更新后的发布检查");
  await expect(panel.getByTestId("prompt-preview")).toContainText("全局");
  await panel.getByRole("button", { name: "编辑", exact: true }).click();
  await panel.getByLabel("模板内容").press("Escape");
  await expect(panel.getByTestId("prompt-form")).toHaveCount(0);
  await expect(settings).toBeVisible();
  page.once("dialog", (dialog) => void dialog.accept());
  await panel.getByRole("button", { name: "删除", exact: true }).click();
  await expect(panel.getByTestId("prompt-item")).toHaveCount(2);
  await settings.getByRole("button", { name: "关闭设置", exact: true }).click();
  await page.getByRole("button", { name: "设置", exact: true }).click();
  await expect(page.getByTestId("prompt-manager").getByTestId("prompt-item")).toHaveCount(2);
  const templates = await studio.api<PromptTemplate[]>("GET", "/api/prompt-templates");
  expect(templates.map((t) => t.title).sort()).toEqual(["每日巡检", "项目检查"].sort());
});
