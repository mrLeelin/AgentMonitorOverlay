import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium, expect, test, type Browser } from "@playwright/test";
import { saveAccount } from "@amo-studio/account";
import { TeamBoardClient, type Workspace, type StateSnapshot } from "@amo-studio/protocol";
import { RelayClient, RelayStore, startRelayServer } from "@amo-studio/relay";
import { startTeamBoardServer } from "@amo-studio/team-board-server";
import { removeTempDir } from "@amo-studio/testkit";
import { launchStudio, screenshot, studioRoot, type Studio } from "../support/studio.js";

test("browser team board shares claims, review notices and comments with the Studio local board", async () => {
  const root = mkdtempSync(join(tmpdir(), "amo-team-board-e2e-"));
  const relayStore = new RelayStore(join(root, "relay.sqlite"));
  let relay: Awaited<ReturnType<typeof startRelayServer>> | undefined;
  let board: Awaited<ReturnType<typeof startTeamBoardServer>> | undefined;
  let browser: Browser | undefined;
  let studio: Studio | undefined;
  try {
    relay = await startRelayServer({ host: "127.0.0.1", port: 0, store: relayStore });
    const auth = new RelayClient(relay.url);
    const password = "team-board-test!";
    const author = await auth.register("陈楠", password);
    const receiver = await auth.register("林舟", password);
    const colleague = await auth.register("周遥", password);
    board = await startTeamBoardServer({ host: "127.0.0.1", port: 0, path: join(root, "board.sqlite"), relay: relay.url, web: join(studioRoot, "packages/team-board-server/dist-web") });
    const url = `http://127.0.0.1:${board.port}`;
    const receiverApi = new TeamBoardClient(url, receiver.key);
    const authorApi = new TeamBoardClient(url, author.key);
    const colleagueApi = new TeamBoardClient(url, colleague.key);
    await expect(new TeamBoardClient(url).snapshot()).rejects.toMatchObject({ status: 401 });
    browser = await chromium.launch({ executablePath: process.env.AMO_TEST_BROWSER_PATH });
    const web = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    const errors: string[] = [];
    web.on("pageerror", (error) => errors.push(error.message));
    await web.goto(url);
    await web.getByLabel("账号", { exact: true }).fill(author.name);
    await web.getByLabel("密码", { exact: true }).fill(password);
    await web.getByRole("button", { name: "登录", exact: true }).click();
    await expect(web.locator("[data-team-column]")).toHaveCount(4);
    await web.getByRole("button", { name: "提交任务", exact: true }).click();
    const form = web.getByRole("region", { name: "提交团队任务" });
    const title = "结算界面偶尔黑屏";
    await form.getByLabel("标题").fill(title);
    await form.getByLabel("说明").fill("连续两局，检查黑屏和返回首页流程。");
    await form.locator('input[type="file"]').setInputFiles({ name: "settlement.txt", mimeType: "text/plain", buffer: Buffer.from("repro log") });
    await form.getByRole("button", { name: "提交到待定" }).click();
    await expect(web.locator('[data-team-column="pending"]')).toContainText(title);
    const ticket = (await receiverApi.snapshot()).tickets.find((entry) => entry.title === title)!;
    expect(ticket.assignee).toBeNull();
    const details = await colleagueApi.detail(ticket.id);
    const file = details.events[0]!.files[0]!;
    expect(Buffer.from(await colleagueApi.file(ticket.id, file.id)).toString()).toBe("repro log");
    await web.getByRole("button", { name: "关闭", exact: true }).click();
    await web.screenshot({ path: join(studioRoot, "screenshots/studio/team-board-web.png") });

    const receiverHome = join(root, "studio-account");
    await saveAccount({ server: relay.url, name: receiver.name, key: receiver.key }, { env: { AMO_HOME: receiverHome } });
    studio = await launchStudio({ mockModel: false, env: { AMO_HOME: receiverHome, AMO_TEAM_BOARD_URL: url } });
    const app = studio.page;
    const project = await studio.api<Workspace>("POST", "/api/workspaces", { path: studio.workspace("JellybeanUnity") });
    await app.getByTestId("scope-ws-JellybeanUnity").click();
    const toolbar = app.locator(".viewbar");
    const titleBar = app.locator(".topbar");
    const nav = app.getByRole("navigation", { name: "范围" });
    const teamButton = nav.getByRole("button", { name: "团队任务", exact: true });
    await expect(toolbar.getByRole("button", { name: "团队任务", exact: true })).toHaveCount(0);
    await expect(titleBar.getByRole("button", { name: "团队任务", exact: true })).toHaveCount(0);
    await expect(nav.locator(".wb-nav-team + [data-testid='scope-all']")).toHaveCount(1);
    await expect(teamButton).toHaveAttribute("aria-pressed", "false");
    await teamButton.click();
    await expect(teamButton).toHaveAttribute("aria-pressed", "true");
    const side = app.getByRole("region", { name: "可领取任务" });
    const source = side.locator(`[data-team-ticket="${ticket.id}"]`);
    await expect(source).toContainText("未指派");
    await expect(toolbar).toHaveCount(0);
    await expect(app.getByTestId("column-todo")).toHaveCount(0);
    const claim = async () => {
      await source.click();
      await app.getByRole("dialog").getByRole("button", { name: "加入本地待办" }).click();
    };
    await claim();
    await expect(side.getByText("暂无可领取的任务")).toBeVisible();
    await teamButton.click();
    const local = app.getByTestId("column-todo").getByTestId("task-card").filter({ hasText: title });
    await expect(local).toBeVisible();
    const initial = await studio.api<StateSnapshot>("GET", "/api/state");
    const task = initial.tasks.find((entry) => entry.title === title)!;
    expect(task.workspaceId).toBe(project.id);
    expect(initial.sessions.some((session) => session.taskId === task.id)).toBe(false);
    await screenshot(studio.app, "studio", "team-board-studio", app);
    const claimed = await receiverApi.detail(ticket.id);
    expect(claimed).toMatchObject({ status: "doing", assignee: "林舟" });
    await expect(colleagueApi.claim(ticket.id, claimed.revision)).rejects.toMatchObject({ status: 409 });
    await local.click();
    await app.getByTestId("sidebar-activity").click();
    const linked = app.getByRole("complementary", { name: "任务侧栏" }).getByRole("region", { name: "关联的团队原单" });
    await linked.getByRole("button", { name: "团队原单", exact: true }).click();
    await linked.getByRole("button", { name: "送审", exact: true }).click();
    await linked.getByLabel("处理说明（选填）").fill("连续两局已验证。");
    await linked.locator("form").getByRole("button", { name: "送审", exact: true }).click();
    await expect(web.getByRole("button", { name: "待审核 1" })).toBeVisible({ timeout: 15_000 });
    await web.getByRole("button", { name: "待审核 1" }).click();
    await web.screenshot({ path: join(studioRoot, "screenshots/studio/team-board-notice.png") });
    await web.getByRole("region", { name: "待审核通知" }).getByRole("button", { name: new RegExp(title) }).click();
    const webDetails = web.getByRole("region", { name: "团队原单", exact: true });
    await expect(webDetails).toContainText("连续两局已验证");
    await web.locator(`[data-team-ticket="${ticket.id}"]`).dragTo(web.locator('[data-team-column="pending"] h3'));
    await expect(web.locator('[data-team-column="pending"]')).toContainText("执行者 林舟");
    await webDetails.getByLabel("评论", { exact: true }).fill("请补一次断网测试。");
    await webDetails.locator("form").getByRole("button", { name: "评论", exact: true }).click();
    await expect(webDetails).toContainText("请补一次断网测试");
    await app.getByTestId("scope-ws-JellybeanUnity").click();
    await teamButton.click();
    await expect(source).toContainText(title, { timeout: 15_000 });
    await claim();
    await expect(app.getByTestId("task-title")).toContainText(title);
    expect((await studio.api<StateSnapshot>("GET", "/api/state")).tasks.filter((entry) => entry.title === title).map((entry) => entry.id)).toEqual([task.id]);
    await app.getByTestId("sidebar-activity").click();
    await linked.getByRole("button", { name: "团队原单", exact: true }).click();
    await expect(linked).toContainText("请补一次断网测试");
    await screenshot(studio.app, "studio", "team-board-local-task", app);
    await linked.getByRole("button", { name: "送审", exact: true }).click();
    await linked.locator("form").getByRole("button", { name: "送审", exact: true }).click();
    await expect(web.locator('[data-team-column="review"]')).toContainText(title, { timeout: 15_000 });
    await web.locator(`[data-team-ticket="${ticket.id}"]`).dragTo(web.locator('[data-team-column="done"] h3'));
    await expect(web.locator('[data-team-column="done"]')).toContainText(title);
    expect((await authorApi.detail(ticket.id)).status).toBe("done");
    const contested = await authorApi.create({ requestId: "parallel-claim", title: "核对重复接单", description: "两个同事同时接单", assignee: colleague.name });
    const attempts = await Promise.allSettled([receiverApi.claim(contested.id, contested.revision), colleagueApi.claim(contested.id, contested.revision)]);
    expect(attempts.filter((result) => result.status === "fulfilled")).toHaveLength(1);
    expect(attempts.find((result) => result.status === "rejected")).toMatchObject({ reason: { status: 409 } });
    await web.setViewportSize({ width: 414, height: 900 });
    expect(await web.evaluate(() => document.documentElement.scrollWidth)).toBe(414);
    expect(errors).toEqual([]);
  } finally {
    await browser?.close();
    await studio?.close();
    await board?.close();
    await relay?.close();
    relayStore.close();
    removeTempDir(root);
  }
});
