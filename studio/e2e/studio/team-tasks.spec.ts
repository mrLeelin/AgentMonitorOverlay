import { mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { _electron, expect, test, type ElectronApplication } from "@playwright/test";
import { saveAccount } from "@amo-studio/account";
import type { LinkedTeamTask, StateSnapshot, Task, Workspace } from "@amo-studio/protocol";
import { RelayClient, RelayStore, startRelayServer, type RelayServer } from "@amo-studio/relay";
import { removeTempDir } from "@amo-studio/testkit";
import { launchStudio, screenshot, studioRoot, windowState, type Studio } from "../support/studio.js";
import { programLaunch } from "../support/packed.js";

test("submits in the desktop client, imports and executes in Studio, and accepts on the persisted origin", async () => {
  const root = mkdtempSync(join(tmpdir(), "amo-team-tasks-e2e-"));
  const db = join(root, "relay.db");
  let store = new RelayStore(db);
  let relay: RelayServer | undefined;
  let desktop: ElectronApplication | undefined;
  let studio: Studio | undefined;
  const start = (port = 0) => startRelayServer({ store, host: "127.0.0.1", port, filesDir: join(root, "files") });
  const newDesktop = (home: string) => {
    const launch = programLaunch("team-tasks-app", join(studioRoot, "packages", "team-tasks-app", "dist", "main.js"));
    return _electron.launch({ ...launch, args: [...launch.args, "--hidden"], env: { ...process.env, AMO_HOME: home, AMO_TEAM_TASKS_HOME: join(root, "team-desktop") } });
  };
  try {
    relay = await start();
    const anonymous = new RelayClient(relay.url);
    const a = await anonymous.register("周遥", "Team-task-test-a!");
    const b = await anonymous.register("林舟", "Team-task-test-b!");
    const c = await anonymous.register("沈岚", "Team-task-test-c!");
    const creator = new RelayClient(relay.url, a.key);
    const receiver = new RelayClient(relay.url, b.key);
    const unrelated = new RelayClient(relay.url, c.key);
    const submitterHome = join(root, "a-account");
    const receiverHome = join(root, "b-account");

    desktop = await newDesktop(submitterHome);
    const submit = await desktop.firstWindow();
    await expect(submit.getByRole("heading", { name: "请先在 AMO 平台里登录" })).toBeVisible();
    expect(await windowState(desktop)).toMatchObject({ visible: false, focused: false, onScreen: false });
    await saveAccount({ server: relay.url, name: a.name, key: a.key }, { env: { AMO_HOME: submitterHome } });
    await saveAccount({ server: relay.url, name: b.name, key: b.key }, { env: { AMO_HOME: receiverHome } });
    await submit.getByRole("button", { name: "刷新", exact: true }).click();
    await expect(submit.getByRole("heading", { name: "新建任务" })).toBeVisible();
    await screenshot(desktop, "studio", "team-tasks-v1-submit", submit);
    const title = "结算界面偶尔黑屏";
    await submit.getByLabel("标题", { exact: true }).fill(title);
    await expect(submit.getByLabel("相关项目")).toHaveCount(0);
    await submit.getByLabel("接收人").selectOption(b.name);
    await submit.getByLabel("说明", { exact: true }).fill("第二局结算后，返回首页前停在黑屏。请验证连续两局。");
    await submit.locator('input[type="file"]').setInputFiles({ name: "settlement.txt", mimeType: "text/plain", buffer: Buffer.from("render event") });
    await submit.getByRole("button", { name: "提交任务", exact: true }).click();
    await expect(submit.getByRole("heading", { name: title })).toBeVisible();
    await expect(submit.getByRole("heading", { name: "新建任务" })).toBeHidden();

    const ticket = await receiver.teamTaskDetail((await receiver.teamTaskList())[0]!.id);
    expect(ticket.project).toBe("");
    const ticketId = ticket.id;
    const file = ticket.events[0]!.files[0]!;
    expect(await unrelated.teamTaskList()).toEqual([]);
    await expect(unrelated.teamTaskDetail(ticketId)).rejects.toMatchObject({ status: 404 });
    await expect(unrelated.teamTaskDownload(ticketId, file.id)).rejects.toMatchObject({ status: 404 });
    await expect(creator.teamTaskChange(ticketId, { action: "start", revision: ticket.revision })).rejects.toMatchObject({ status: 403 });
    expect(Buffer.from(await receiver.teamTaskDownload(ticketId, file.id)).toString()).toBe("render event");

    studio = await launchStudio({ env: { AMO_HOME: receiverHome } });
    const page = studio.page;
    const project = await studio.api<Workspace>("POST", "/api/workspaces", { path: studio.workspace("JellybeanUnity") });
    await studio.api<Workspace>("POST", "/api/workspaces", { path: studio.workspace("AmoStudio") });
    await page.getByTestId("scope-all").click();
    await page.getByRole("button", { name: "团队任务", exact: true }).click();
    const inbox = page.getByRole("complementary", { name: "团队任务收件箱" });
    await expect(inbox.getByRole("button", { name: "settlement.txt", exact: true })).toBeVisible();
    const target = inbox.getByLabel("加入本地项目");
    await expect(target).toHaveValue("");
    await expect(page.getByTestId("team-task-drop")).toHaveCount(0);
    await expect(inbox.getByRole("button", { name: "加入本地待办", exact: true })).toBeDisabled();
    await target.selectOption(project.id);
    const originalFile = join(root, "saved-settlement.txt");
    await studio.app.evaluate(({ dialog }, path) => { dialog.showSaveDialog = (async () => ({ canceled: false, filePath: path })) as typeof dialog.showSaveDialog; }, originalFile);
    await inbox.getByRole("button", { name: "settlement.txt", exact: true }).click();
    await expect.poll(() => { try { return readFileSync(originalFile, "utf8"); } catch { return ""; } }).toBe("render event");
    await screenshot(studio.app, "studio", "team-tasks-v1-inbox", page);
    await inbox.getByRole("button", { name: new RegExp(title) }).dragTo(page.getByTestId("team-task-drop"));
    const card = page.getByTestId("column-todo").getByTestId("task-card").filter({ hasText: title });
    await expect(card).toBeVisible();
    const local = (await studio.api<StateSnapshot>("GET", "/api/state")).tasks.find((item) => item.title === title)!;
    expect(local.workspaceId).toBe(project.id);
    expect((await studio.api<{ task: Task; existing: boolean }>("POST", `/api/team-tasks/${ticketId}/import`, { workspaceId: project.id }))).toMatchObject({ task: { id: local.id }, existing: true });
    expect((await receiver.teamTaskDetail(ticketId)).status).toBe("pending");
    await screenshot(studio.app, "studio", "team-tasks-v1-imported", page);

    await card.click();
    await page.getByTestId("new-session-toggle").click();
    await page.getByRole("button", { name: "开始新会话", exact: true }).click();
    const composer = page.getByLabel("输入消息");
    await expect(composer).toContainText("第二局结算后");
    expect((await receiver.teamTaskDetail(ticketId)).status).toBe("pending");
    await composer.press("Enter");
    await expect(page.getByTestId("msg-agent").first()).toBeVisible({ timeout: 30_000 });
    await expect.poll(async () => (await receiver.teamTaskDetail(ticketId)).status).toBe("doing");
    await page.getByRole("button", { name: "团队原单", exact: true }).click();
    const original = page.getByRole("region", { name: "团队原单", exact: true });
    await original.getByRole("button", { name: "提交结果", exact: true }).click();
    await original.getByLabel("处理说明和验证结果").fill("已检查结算，连续两局正常。");
    await original.locator('input[type="file"]').setInputFiles({ name: "verification.txt", mimeType: "text/plain", buffer: Buffer.from("two rounds") });
    await original.getByRole("button", { name: "提交给验收人", exact: true }).click();
    await expect(original).toContainText("待验收");
    await submit.getByRole("button", { name: "刷新", exact: true }).click();
    await expect(submit.getByRole("button", { name: "verification.txt", exact: true })).toBeVisible();
    await expect(submit.getByRole("heading", { name: "新建任务" })).toBeHidden();
    const resultFile = join(root, "saved-verification.txt");
    await desktop.evaluate(({ dialog }, path) => { dialog.showSaveDialog = (async () => ({ canceled: false, filePath: path })) as typeof dialog.showSaveDialog; }, resultFile);
    await submit.getByRole("button", { name: "verification.txt", exact: true }).click();
    await expect.poll(() => { try { return readFileSync(resultFile, "utf8"); } catch { return ""; } }).toBe("two rounds");
    await screenshot(desktop, "studio", "team-tasks-v1-review", submit);
    await submit.getByRole("button", { name: "发回继续处理", exact: true }).click();
    await submit.getByLabel("还需要处理什么？").fill("请再补断网场景。");
    await submit.getByRole("button", { name: "发送", exact: true }).click();
    await expect(submit.getByRole("status")).toHaveText("已发回继续处理");
    await original.getByRole("button", { name: "刷新原单" }).click();
    await expect(original).toContainText("请再补断网场景");
    await original.getByRole("button", { name: "提交结果", exact: true }).click();
    await original.getByLabel("处理说明和验证结果").fill("已补断网测试。");
    await original.getByRole("button", { name: "提交给验收人", exact: true }).click();
    await expect(original).toContainText("待验收");
    await submit.getByRole("button", { name: "刷新", exact: true }).click();
    await expect(submit.getByRole("region", { name: "任务详情" })).toContainText("已补断网测试");
    await submit.getByRole("button", { name: "确认完成", exact: true }).click();
    await expect(submit.getByRole("status")).toHaveText("已确认完成");
    const linked = await studio.api<LinkedTeamTask>("GET", `/api/team-tasks/local/${local.id}`);
    expect(linked.ticket.status).toBe("done");
    expect((await studio.api<StateSnapshot>("GET", "/api/state")).tasks.find((task) => task.id === local.id)?.column).toBe("done");

    await desktop.close();
    desktop = undefined;
    const port = relay.port;
    await relay.close();
    relay = undefined;
    store.close();
    store = new RelayStore(db);
    relay = await start(port);
    await saveAccount({ server: relay.url, name: a.name, key: a.key }, { env: { AMO_HOME: submitterHome } });
    desktop = await newDesktop(submitterHome);
    const reopened = await desktop.firstWindow();
    await reopened.getByRole("button", { name: new RegExp(title) }).click();
    await expect(reopened.getByRole("region", { name: "任务详情" })).toContainText("已完成");
    await expect(reopened.getByRole("button", { name: "settlement.txt", exact: true })).toBeVisible();
    expect((await new RelayClient(relay.url, a.key).teamTaskDetail(ticketId)).events.map((entry) => entry.action)).toEqual(["create", "start", "deliver", "return", "deliver", "accept"]);
    const studioData = studio.root;
    await studio.close({ keepData: true });
    studio = await launchStudio({ root: studioData, env: { AMO_HOME: receiverHome } });
    await expect.poll(async () => (await studio!.api<LinkedTeamTask>("GET", `/api/team-tasks/local/${local.id}`).catch(() => null))?.ticket.status).toBe("done");
  } finally {
    await desktop?.close();
    await studio?.close();
    await relay?.close();
    store.close();
    removeTempDir(root);
  }
});
