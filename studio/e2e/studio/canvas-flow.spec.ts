import { expect, test } from "@playwright/test";
import type { CanvasDoc, Session, StateSnapshot, Task, TaskResult, Topic, Workspace } from "@amo-studio/protocol";
import { launchStudio, screenshot, type Studio } from "../support/studio.js";

let studio: Studio | undefined;
test.afterEach(async () => { await studio?.close(); studio = undefined; });

test("canvas arrows follow real execution, delivery, return and acceptance, with motion controls", async () => {
  studio = await launchStudio();
  const { page, app } = studio;
  const ws = await studio.api<Workspace>("POST", "/api/workspaces", { path: studio.workspace("canvas-flow") });
  const topic = await studio.api<Topic>("POST", "/api/topics", { title: "任务流转动画" });
  const create = (title: string, lead: boolean, managerTaskId?: string) => studio!.api<{ task: Task; session: Session }>("POST", "/api/tasks", { title, lead, managerTaskId, workspaceId: ws.id, topicId: topic.id, firstSession: { profileId: "codex-mock", text: "登记任务，等待后续工作。" } });
  const root = await create("游戏开发主控", true);
  const worker = await create("制作投币音效", false, root.task.id);
  const next = await create("接入游戏播放", false, root.task.id);
  const tasks = [root.task, worker.task, next.task];
  for (const task of tasks) await studio.api("PUT", `/api/tasks/${task.id}/canvas`, { onCanvas: true });
  const doc = await studio.api<CanvasDoc>("GET", `/api/topics/${topic.id}/canvas`);
  const positions = [{ x: 310, y: 40 }, { x: 90, y: 290 }, { x: 540, y: 290 }];
  await studio.api("PUT", `/api/topics/${topic.id}/canvas`, { ...doc, nodes: doc.nodes.map((n) => ({ ...n, pos: positions[tasks.findIndex((t) => n.kind === "task" && n.taskId === t.id)] ?? n.pos })), edges: [{ id: "sound-to-play", kind: "depends", from: worker.task.id, to: next.task.id }] });
  await page.getByRole("button", { name: "画布", exact: true }).click();
  await expect(page.getByTestId("canvas-card")).toHaveCount(3);
  await page.getByRole("button", { name: "侧栏", exact: true }).click();
  await page.getByRole("button", { name: "全部", exact: true }).click();
  const flow = page.locator(`[data-flow-task-id="${worker.task.id}"]`).getByTestId("canvas-task-flow");
  const idle = async () => expect.poll(async () => (await studio!.api<StateSnapshot>("GET", "/api/state")).sessions.find((s) => s.id === worker.session.id)?.status).toMatch(/idle|completed/);
  await idle();
  await studio.api("POST", `/api/sessions/${worker.session.id}/messages`, { text: "制作中 [[slow]]" });
  await expect(flow).toHaveAttribute("data-direction", "forward");
  const pulse = flow.locator(".canvas-flow-pulse");
  const offset = await pulse.evaluate((el) => getComputedStyle(el).strokeDashoffset);
  await expect.poll(() => pulse.evaluate((el) => getComputedStyle(el).strokeDashoffset)).not.toBe(offset);
  await page.emulateMedia({ reducedMotion: "reduce" });
  await expect(pulse).toHaveCSS("animation-name", "none");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.getByRole("checkbox", { name: "流转动画", exact: true }).uncheck();
  await expect(flow.locator(".canvas-flow-pulse")).toHaveCount(0);
  await expect(flow).toContainText("执行中");
  await page.getByRole("checkbox", { name: "流转动画", exact: true }).check();
  await screenshot(app, "studio", "canvas-flow-running", page);
  await studio.api("POST", `/api/sessions/${worker.session.id}/interrupt`);
  await idle();
  const submit = () => studio!.api<TaskResult>("POST", `/api/tasks/${worker.task.id}/workflow/submit`, { sessionId: worker.session.id, summary: "投币音效已制作", verification: "检查触发时机与播放次数。" });
  const result = await submit();
  await expect(flow).toHaveAttribute("data-direction", "reverse");
  await expect(flow).toContainText("待验收");
  await expect(flow.locator(".canvas-flow-pulse")).toHaveCSS("animation-name", "canvas-flow-reverse");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await expect(flow.locator(".canvas-flow-pulse")).toHaveCSS("animation-name", "none");
  await page.emulateMedia({ reducedMotion: "no-preference", colorScheme: "dark" });
  await screenshot(app, "studio", "canvas-flow-submitted", page);
  await page.getByRole("checkbox", { name: "流转动画", exact: true }).uncheck();
  await page.reload();
  await expect(page.getByRole("checkbox", { name: "流转动画", exact: true })).not.toBeChecked();
  await page.getByRole("checkbox", { name: "流转动画", exact: true }).check();
  await studio.api("POST", `/api/tasks/${root.task.id}/workflow/review`, { sessionId: root.session.id, resultId: result.id, accept: false, review: "缩短尾音，重新交付。" });
  await expect(flow).toHaveAttribute("data-state", "returned");
  await expect(flow).toContainText("退回修改");
  await idle();
  const revised = await submit();
  await studio.api("POST", `/api/tasks/${root.task.id}/workflow/review`, { sessionId: root.session.id, resultId: revised.id, accept: true, review: "验证通过。" });
  await expect(flow).toHaveAttribute("data-state", "accepted");
  await expect(flow.locator(".canvas-flow-pulse")).toHaveCount(0);
  await expect(page.getByTestId("canvas-task-flow").filter({ hasText: "前置已完成" })).toHaveCount(1);
  await screenshot(app, "studio", "canvas-flow-accepted", page);
  await studio.api("POST", `/api/sessions/${next.session.id}/messages`, { text: "接入播放 [[slow]]" });
  const dependency = page.getByTestId("canvas-edge").locator("..").getByTestId("canvas-task-flow");
  await expect(dependency).toHaveAttribute("data-direction", "forward");
  await expect(dependency).toContainText("后续执行中");
  await page.getByRole("checkbox", { name: "管理 ⇢ 虚线" }).uncheck();
  await expect(flow).toHaveCount(0);
  await expect(page.getByTestId("canvas-edge")).toHaveCount(1);
});
