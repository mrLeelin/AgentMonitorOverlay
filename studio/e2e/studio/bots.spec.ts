test("the project agent sends context through MCP, receives the Bot reply and answers in the origin", async () => {
  studio = await launchStudio({ taskSidebar: false, mockScript: (req) => {
    if (req.afterToolOutput && req.lastTool?.name.includes("bot_ask")) return { kind: "text", text: "已把第二个方案交给审核员检查。" };
    const mention = /mentionId 为 ([\w-]+)/.exec(req.lastUserText);
    if (mention) return defaultScript({ ...req, lastUserText: `[[mcp: bot_ask ${JSON.stringify({ mentionId: mention[1], text: "请审查第二个方案的重试逻辑" })}]]` });
    if (req.lastUserText.includes("【Bot 来信】")) return { kind: "text", text: "重试应沿用同一编号。" };
    if (req.lastUserText.includes("【Bot 回信】") && req.lastUserText.includes("重试应沿用同一编号")) return { kind: "text", text: "我已核对审核员的结论，第二个方案可以保留。" };
    return defaultScript(req);
  } });
  const { page, app } = studio;
  await studio.api("POST", "/api/bots", { name: "审核员", purpose: "审核代码", memory: "", profileId: "codex-mock", workspaceId: null, enabled: true });
  await studio.api("POST", "/api/tasks", { title: "讨论方案", firstSession: { profileId: "codex-mock" } });
  await page.getByTestId("task-card").filter({ hasText: "讨论方案" }).click();
  const input = page.getByRole("textbox", { name: "输入消息" });
  await input.pressSequentially("@");
  await page.getByRole("option", { name: /审核员/ }).click();
  await input.pressSequentially("请审第二个方案，回来告诉我结论");
  await input.press("Enter");
  await expect(page.getByText("我已核对审核员的结论，第二个方案可以保留。", { exact: true })).toBeVisible({ timeout: 45000 });
  const reply = page.getByTestId("bot-request");
  await expect(reply).toHaveCount(1);
  const continuation = page.getByText("我已核对审核员的结论，第二个方案可以保留。", { exact: true });
  expect(await reply.evaluate((el, answer) => !!(el.compareDocumentPosition(answer as Node) & Node.DOCUMENT_POSITION_FOLLOWING), await continuation.elementHandle())).toBe(true);
  await expect(reply.locator("summary")).toContainText("请审查第二个方案的重试逻辑");
  await expect(reply.locator(".bot-reply-body")).toBeHidden();
  await reply.locator("summary").click();
  await expect(reply.locator(".bot-reply-body")).toContainText("重试应沿用同一编号。");
  await reply.locator("summary").click();
  await input.fill("然后呢？");
  await input.press("Enter");
  const later = page.getByTestId("msg-user").filter({ hasText: "然后呢？" });
  await expect(later).toBeVisible();
  expect(await reply.evaluate((el, later) => !!(el.compareDocumentPosition(later as Node) & Node.DOCUMENT_POSITION_FOLLOWING), await later.elementHandle())).toBe(true);
  await expect(reply.locator(".bot-reply-body")).toBeHidden();
  await expect(page.getByTestId("msg-user").locator(".bot-mention-chip").filter({ hasText: "审核员" })).toBeVisible();
  await screenshot(app, "studio", "bot-agent-reply", page);
});

