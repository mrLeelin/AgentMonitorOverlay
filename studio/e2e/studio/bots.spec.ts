for (const profileId of ["claude-mock", "dsh-mock"]) {
  test(`Bot uses the selected ${profileId} model and delivers its answer`, async () => {
    studio = await launchStudio({ dsh: profileId === "dsh-mock" });
    const catalog = await studio.api<{ models: { id: string; efforts: string[] }[] }>("GET", `/api/profiles/${profileId}/choices`);
    const model = catalog.models.find((m) => m.efforts.length) ?? catalog.models[0]!;
    const effort = model.efforts.at(-1) ?? null;
    const bot = await studio.api<StudioBot>("POST", "/api/bots", { name: "模型验证", purpose: "检查文本", memory: "", profileId, model: model.id, effort, workspaceId: null, enabled: true });
    await studio.api("POST", `/api/bots/${bot.id}/requests`, { id: "verify-model", text: "请回复你好" });
    await expect.poll(async () => (await studio!.api<BotRequest[]>("GET", "/api/bot-requests"))[0]?.status, { timeout: 45_000 }).toBe("completed");
    const [chat] = await studio.api<Session[]>("GET", `/api/bots/${bot.id}/chats`);
    expect(chat).toMatchObject({ profileId, options: { model: model.id, ...(effort ? { effort } : {}), permission: profileId === "claude-mock" ? "plan" : "read-only" } });
    const changed = await studio.api<Session>("PATCH", `/api/sessions/${chat!.id}/options`, { permission: profileId === "claude-mock" ? "bypassPermissions" : "full-access" });
    expect(changed.options.permission).toBe(chat!.options.permission);
    expect((await studio.api<BotRequest[]>("GET", "/api/bot-requests"))[0]?.result).toBeTruthy();
  });
}

