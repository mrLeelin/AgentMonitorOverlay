import { expect, test } from "@playwright/test";
import type { CanvasDoc, StateSnapshot, Task, Topic, Workspace } from "@amo-studio/protocol";
import { launchStudio, screenshot, type Studio } from "../support/studio.js";

let studio: Studio | undefined;
test.afterEach(async () => { await studio?.close(); studio = undefined; });

test("management: hierarchy, independent line types, selection, level expansion, assignment and transfer", async () => {
  studio = await launchStudio();
  const { page, app } = studio;
  const ws = await studio.api<Workspace>("POST", "/api/workspaces", { path: studio.workspace("hierarchy") });
  const topic = await studio.api<Topic>("POST", "/api/topics", { title: "主控管理与画板关系" });
  const create = async (title: string, lead = false, managerTaskId?: string) => (await studio!.api<{ task: Task }>("POST", "/api/tasks", { title, workspaceId: ws.id, topicId: topic.id, lead, managerTaskId })).task;
  const root = await create("游戏开发主控", true);
  const child = await create("玩法主控", true, root.id);
  const worker = await create("关卡执行", false, child.id);
  const direct = await create("界面执行", false, root.id);
  const peer = await create("独立美术主控", true);
  const tasks = [root, child, worker, direct, peer];
  for (const task of tasks) await studio.api("PUT", `/api/tasks/${task.id}/canvas`, { onCanvas: true });
  const doc = await studio.api<CanvasDoc>("GET", `/api/topics/${topic.id}/canvas`);
  const nodeFor = (id: string) => doc.nodes.find((n) => n.kind === "task" && n.taskId === id)!;
  const positions = [{ x: 280, y: 40 }, { x: 70, y: 230 }, { x: 70, y: 425 }, { x: 350, y: 250 }, { x: 650, y: 40 }];
  await studio.api("PUT", `/api/topics/${topic.id}/canvas`, { ...doc, nodes: doc.nodes.map((n) => ({ ...n, pos: positions[tasks.findIndex((t) => n.kind === "task" && t.id === n.taskId)] ?? n.pos })), edges: [{ id: "dependency", kind: "depends", from: worker.id, to: direct.id }], links: [{ id: "ordinary", from: nodeFor(child.id).id, to: nodeFor(direct.id).id, fromSide: "right", toSide: "left", label: "保留的普通线说明" }, { id: "collaboration", kind: "collaboration", from: nodeFor(root.id).id, to: nodeFor(peer.id).id, fromSide: "right", toSide: "left", label: "美术协作" }] });
  await page.getByRole("button", { name: "画布", exact: true }).click();
  await expect(page.getByTestId("canvas-card")).toHaveCount(5);
  await page.getByRole("button", { name: "全部", exact: true }).click();
  await expect(page.getByTestId("canvas-management-line")).toHaveCount(3);
  await expect(page.getByTestId("canvas-edge")).toHaveCount(1);
  await expect(page.getByTestId("canvas-link")).toHaveCount(1);
  await expect(page.getByTestId("canvas-collaboration-line")).toHaveCount(0);
  const rootCard = page.getByRole("button", { name: root.title, exact: true });
  await expect(rootCard.getByTestId("canvas-management-summary")).toContainText("直属主控 1 · 下辖执行 2");
  await rootCard.click();
  await expect(page.getByTestId("canvas-collaboration-line")).toHaveCount(1);
  await expect(page.getByTestId("canvas-collaboration-line")).not.toHaveAttribute("marker-end");
  await expect(page.getByRole("button", { name: peer.title, exact: true })).toHaveClass(/management-dimmed/);
  await expect(page.getByTestId("canvas-detail")).toContainText("全部下辖 3 个");
  await screenshot(app, "studio", "task-management-hierarchy", page);
  await page.getByRole("combobox", { name: "添加协作任务" }).selectOption(nodeFor(direct.id).id);
  await expect.poll(async () => (await studio!.api<CanvasDoc>("GET", `/api/topics/${topic.id}/canvas`)).links?.filter((l) => l.kind === "collaboration").length).toBe(2);
  await expect(page.getByTestId("canvas-collaboration-line")).toHaveCount(2);
  await page.getByTestId("canvas-detail").locator(".dep-row").filter({ hasText: direct.title }).getByRole("button", { name: "解除协作" }).click();
  await expect.poll(async () => (await studio!.api<CanvasDoc>("GET", `/api/topics/${topic.id}/canvas`)).links?.filter((l) => l.kind === "collaboration").length).toBe(1);
  await expect(page.getByTestId("canvas-link")).toHaveCount(1);
  await expect(page.getByTestId("canvas-edge")).toHaveCount(1);
  await page.getByRole("button", { name: "收起间接下辖" }).click();
  await expect(page.getByTestId("canvas-card")).toHaveCount(4);
  await expect(page.getByTestId("canvas-management-line")).toHaveCount(2);
  await page.getByRole("button", { name: "展开全部层级" }).click();
  await expect(page.getByTestId("canvas-card")).toHaveCount(5);
  await page.getByRole("checkbox", { name: "管理 ⇢ 虚线" }).uncheck();
  await expect(page.getByTestId("canvas-management-line")).toHaveCount(0);
  await expect(page.getByTestId("canvas-edge")).toHaveCount(1);
  await expect(page.getByTestId("canvas-link")).toHaveCount(1);
  await page.getByRole("checkbox", { name: "管理 ⇢ 虚线" }).check();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "按管理层级排列" }).click();
  await expect.poll(async () => {
    const next = await studio!.api<CanvasDoc>("GET", `/api/topics/${topic.id}/canvas`);
    const y = (id: string) => next.nodes.find((n) => n.kind === "task" && n.taskId === id)!.pos.y;
    return y(root.id) < y(child.id) && y(child.id) < y(worker.id) && y(child.id) === y(direct.id);
  }).toBe(true);
  await page.getByRole("button", { name: "全部", exact: true }).click();
  await screenshot(app, "studio", "task-management-layout", page);
  const workerCard = page.getByRole("button", { name: worker.title, exact: true });
  await workerCard.getByRole("button", { name: `直属：${child.title}` }).click();
  await expect(page.getByTestId("canvas-detail")).toContainText(child.title);
  await page.keyboard.press("Escape");
  await workerCard.dblclick();
  await page.getByTestId("task-management-toggle").click();
  await page.getByRole("combobox", { name: "直属主控", exact: true }).selectOption(peer.id);
  await expect.poll(async () => (await studio!.api<StateSnapshot>("GET", "/api/state")).tasks.find((t) => t.id === worker.id)?.managerTaskId).toBe(peer.id);
  await expect(page.getByTestId("task-management-toggle")).toContainText(peer.title);
  await screenshot(app, "studio", "task-management-transfer", page);
  await page.getByRole("combobox", { name: "直属主控", exact: true }).selectOption("");
  await expect.poll(async () => (await studio!.api<StateSnapshot>("GET", "/api/state")).tasks.find((t) => t.id === worker.id)?.managerTaskId).toBeNull();
});
